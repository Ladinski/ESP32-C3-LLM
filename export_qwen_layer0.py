"""Export genuine pretrained Qwen2.5-0.5B layer 0 to ESP32 C3 paged INT4 image.
Offline PC conversion only; ESP32 performs all runtime neural calculations.
"""
import argparse, hashlib, json, struct, mmap
from pathlib import Path
import numpy as np

REPO='Qwen/Qwen2.5-0.5B'
D=896; KV=128; FF=4864; PAGE=512
TOKENS=(100,200)
MATS=(('q_proj',D,D),('k_proj',KV,D),('v_proj',KV,D),('o_proj',D,D),('gate_proj',FF,D),('up_proj',FF,D),('down_proj',D,FF))
HEADER=128


class BFloatReader:
    """Minimal read-only safetensors BF16 reader; mmap avoids loading the 988 MB model into RAM."""
    def __init__(self,path):
        self.f=open(path,'rb');self.mm=mmap.mmap(self.f.fileno(),0,access=mmap.ACCESS_READ)
        header_bytes=struct.unpack_from('<Q',self.mm,0)[0]
        if header_bytes>10_000_000:raise ValueError('Invalid safetensors header length')
        self.meta=json.loads(self.mm[8:8+header_bytes]);self.data_begin=8+header_bytes
    def __enter__(self):return self
    def __exit__(self,*args):self.mm.close();self.f.close()
    def _decode(self,raw,dtype,shape):
        if dtype=='BF16':
            raw16=np.frombuffer(raw,dtype='<u2')
            return (raw16.astype(np.uint32)<<16).view(np.float32).reshape(shape)
        if dtype=='F32':return np.frombuffer(raw,dtype='<f4').copy().reshape(shape)
        if dtype=='F16':return np.frombuffer(raw,dtype='<f2').astype(np.float32).reshape(shape)
        raise ValueError('Unsupported pretrained tensor dtype: '+dtype)
    def get_tensor(self,key):
        t=self.meta[key];a,b=t['data_offsets']
        return self._decode(self.mm[self.data_begin+a:self.data_begin+b],t['dtype'],t['shape'])
    def get_row(self,key,index):
        t=self.meta[key];rows,cols=t['shape']
        if not 0<=index<rows:raise IndexError(index)
        width={'BF16':2,'F16':2,'F32':4}[t['dtype']]*cols
        a=t['data_offsets'][0]+index*width
        return self._decode(self.mm[self.data_begin+a:self.data_begin+a+width],t['dtype'],(cols,))

def export():
    from huggingface_hub import hf_hub_download
    print('Downloading/reusing official Qwen2.5-0.5B safetensors (~988 MB); no PyTorch required',flush=True)
    checkpoint=hf_hub_download(REPO,'model.safetensors')
    path=Path('phase24_qwen_layer0_int4.bin')
    offsets={}; mats=[]
    with BFloatReader(checkpoint) as sf, path.open('wb') as f:
        f.write(bytes(HEADER))
        def write_arr(label,vec):
            offsets[label]=f.tell()
            arr=np.asarray(vec,dtype='<f4').reshape(-1)
            f.write(arr.tobytes())
            print(label,offsets[label],arr.size,flush=True)
        for i,token in enumerate(TOKENS):write_arr('embedding'+str(i),sf.get_row('model.embed_tokens.weight',token))
        write_arr('norm1',sf.get_tensor('model.layers.0.input_layernorm.weight'))
        write_arr('norm2',sf.get_tensor('model.layers.0.post_attention_layernorm.weight'))
        for name in ('q_proj','k_proj','v_proj'):
            write_arr('bias_'+name,sf.get_tensor('model.layers.0.self_attn.'+name+'.bias'))
        for name,rows,cols in MATS:
            key='model.layers.0.'+('self_attn.' if name in ('q_proj','k_proj','v_proj','o_proj') else 'mlp.')+name+'.weight'
            matrix=np.asarray(sf.get_tensor(key),dtype=np.float32)
            if matrix.shape!=(rows,cols):raise RuntimeError(f'{key}: got {matrix.shape}; expected {(rows,cols)}')
            offsets['matrix_'+name]=f.tell()
            bytes_per_row=cols//2+4
            for r in range(rows):
                row=matrix[r]
                peak=float(np.max(np.abs(row)))
                scale=np.float32(peak/7. if peak else 1.)
                ints=np.clip(np.rint(row/scale),-8,7).astype(np.int8)
                packed=((ints[0::2].astype(np.uint8)&15)|((ints[1::2].astype(np.uint8)&15)<<4))
                f.write(packed.tobytes());f.write(struct.pack('<f',float(scale)))
            mats.append({'name':name,'rows':rows,'cols':cols,'offset':offsets['matrix_'+name], 'row_bytes':bytes_per_row})
            print('INT4 matrix',name,'rows',rows,'cols',cols, 'offset',offsets['matrix_'+name],flush=True)
            del matrix
        size=f.tell()
        f.seek(0)
        f.write(struct.pack('<4s7I',b'QW24',1,D,KV,FF,PAGE,len(TOKENS),size))
    with path.open('rb') as f:
        digest=hashlib.file_digest(f,'sha256').hexdigest()
    meta={'model':REPO,'source':'official pretrained BF16 safetensors','quantization':'symmetric per-output-row INT4 scale float32','input_token_ids':list(TOKENS),'size':size,'sha256':digest,'offsets':offsets,'matrices':mats}
    Path('phase24_qwen_layer0_int4.json').write_text(json.dumps(meta,indent=2),encoding='utf-8')
    def hx(n):return f'{n}U'
    header='''// GENERATED by export_qwen_layer0.py. Regenerate if model image changes.
#pragma once
#include <stdint.h>
#define P24_IMAGE_SIZE %s
#define P24_PAGE 512U
#define P24_D 896
#define P24_KV 128
#define P24_FF 4864
static const uint32_t p24_embed[2]={%s};
static const uint32_t p24_norm[2]={%s};
static const uint32_t p24_bias[3]={%s};
static const uint32_t p24_matrix_bases[7]={%s};
static const uint32_t p24_matrix_rows[7]={896,128,128,896,4864,4864,896};
static const uint32_t p24_matrix_cols[7]={896,896,896,896,896,896,4864};
'''%(hx(size),','.join(map(hx,[offsets['embedding0'],offsets['embedding1']])),','.join(map(hx,[offsets['norm1'],offsets['norm2']])),','.join(map(hx,[offsets['bias_q_proj'],offsets['bias_k_proj'],offsets['bias_v_proj']])),','.join(map(hx,[offsets['matrix_'+m[0]] for m in MATS])))
    Path('main').mkdir(exist_ok=True)
    Path('main/phase24_layout.h').write_text(header,encoding='utf-8')
    print(f'EXPORT PASS | {size:,} bytes | SHA256 {digest}\nWrote phase24_qwen_layer0_int4.json and main/phase24_layout.h')

if __name__=='__main__':export()
