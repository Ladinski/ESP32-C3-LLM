"""Offline Qwen2.5-0.5B stack exporter. Runtime inference is exclusively on ESP32-C3."""
import argparse, json, hashlib, struct
from pathlib import Path
import numpy as np
from export_qwen_layer0 import BFloatReader, REPO, D, KV, FF, PAGE, TOKENS, MATS


def main():
    p=argparse.ArgumentParser()
    p.add_argument('--layers',type=int,default=2,help='2 for first hardware gate; 24 for full transformer stack')
    p.add_argument('--checkpoint',default=None,help='Optional existing official model.safetensors path')
    a=p.parse_args()
    if not 1<=a.layers<=24:raise ValueError('layers must be 1..24')
    if a.checkpoint:checkpoint=a.checkpoint
    else:
        from huggingface_hub import hf_hub_download
        print('Locating official Qwen2.5-0.5B checkpoint in HF cache...',flush=True)
        checkpoint=hf_hub_download(REPO,'model.safetensors')
    stem=f'phase25_qwen_{a.layers}layers_int4'
    image=Path(stem+'.bin'); offsets={}; layers=[]
    with BFloatReader(checkpoint) as sf, image.open('wb') as out:
        out.write(bytes(128))
        def arr(label,values):
            offset=out.tell()
            v=np.asarray(values,dtype='<f4').reshape(-1)
            out.write(v.tobytes())
            return offset
        embeddings=[arr('embedding'+str(i),sf.get_row('model.embed_tokens.weight',token)) for i,token in enumerate(TOKENS)]
        for layer_id in range(a.layers):
            prefix=f'model.layers.{layer_id}.'
            norms=[arr('norm1',sf.get_tensor(prefix+'input_layernorm.weight')),
                   arr('norm2',sf.get_tensor(prefix+'post_attention_layernorm.weight'))]
            biases=[arr('bias'+name,sf.get_tensor(prefix+'self_attn.'+name+'.bias')) for name in ('q_proj','k_proj','v_proj')]
            matrices=[]
            for name,rows,cols in MATS:
                key=prefix+('self_attn.' if name in ('q_proj','k_proj','v_proj','o_proj') else 'mlp.')+name+'.weight'
                mat=sf.get_tensor(key)
                if mat.shape!=(rows,cols):raise RuntimeError(f'{key}: invalid shape {mat.shape}')
                off=out.tell();width=cols//2+4
                for row in mat:
                    mx=float(np.max(np.abs(row)));scale=np.float32(mx/7 if mx else 1)
                    q=np.clip(np.rint(row/scale),-8,7).astype(np.int8)
                    packed=(q[::2].astype(np.uint8)&15)|((q[1::2].astype(np.uint8)&15)<<4)
                    out.write(packed.tobytes());out.write(struct.pack('<f',float(scale)))
                matrices.append({'name':name,'rows':rows,'cols':cols,'offset':off,'row_bytes':width})
                del mat
            layers.append({'index':layer_id,'norms':norms,'biases':biases,'matrices':matrices})
            print(f'Exported real pretrained layer {layer_id+1}/{a.layers}: image now {out.tell():,} bytes',flush=True)
        size=out.tell()
        out.seek(0);out.write(struct.pack('<4s7I',b'QW25',1,D,KV,FF,PAGE,a.layers,size))
    with image.open('rb') as f:sha=hashlib.file_digest(f,'sha256').hexdigest()
    metadata={'model':REPO,'source':'official pretrained checkpoint (offline INT4 conversion)','quantization':'symmetric INT4 per row with float32 scale','image_size':size,'sha256':sha,'layers':layers,'embeddings':embeddings,'input_token_ids':list(TOKENS),'page':PAGE,'model_layers_total':24}
    Path(stem+'.json').write_text(json.dumps(metadata,indent=2),encoding='utf-8')
    def u(x):return str(x)+'U'
    s='''// GENERATED by export_qwen_stack.py - tied to this exported image.
#pragma once
#include <stdint.h>
#define P25_IMAGE_SIZE %s
#define P25_PAGE 512U
#define P25_D 896
#define P25_KV 128
#define P25_FF 4864
#define P25_LAYERS %d
static const uint32_t p25_embeds[2]={%s};
typedef struct {uint32_t norm[2];uint32_t bias[3];uint32_t matrix[7];} p25_layout_t;
static const p25_layout_t p25_layouts[P25_LAYERS]={
'''%(u(size),a.layers,','.join(map(u,embeddings)))
    for L in layers:
        s+='  {{'+','.join(map(u,L['norms']))+'},{'+','.join(map(u,L['biases']))+'},{'+','.join(u(m['offset']) for m in L['matrices'])+'}},\n'
    s+='};\nstatic const uint32_t p25_matrix_rows[7]={896,128,128,896,4864,4864,896};\nstatic const uint32_t p25_matrix_cols[7]={896,896,896,896,896,896,4864};\n'
    Path('main').mkdir(exist_ok=True)
    Path('main/phase25_layout.h').write_text(s,encoding='utf-8')
    print(f'PHASE 25 EXPORT PASS: {a.layers} pretrained layers, {size:,} bytes SHA256 {sha}',flush=True)
    print(f'Produced {image} {stem}.json main/phase25_layout.h',flush=True)
if __name__=='__main__':main()
